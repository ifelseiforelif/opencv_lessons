"""
09. Малювання ліній, прямокутників, кіл та тексту на зображенні.
Такі функції використовують для візуалізації результатів комп'ютерного зору.
"""
import cv2
import numpy as np

# Створюємо чисте полотно висотою 500, шириною 700, три канали BGR.
canvas = np.zeros((500, 700, 3), dtype=np.uint8)

# Заливаємо полотно світло-сірим кольором.
canvas[:] = (230, 230, 230)

# Лінія: початкова точка, кінцева точка, колір BGR, товщина.
cv2.line(canvas, (40, 50), (250, 50), (255, 0, 0), 4)

# Прямокутник: дві протилежні вершини.
# Товщина -1 означає, що прямокутник буде заповнений.
cv2.rectangle(canvas, (40, 90), (250, 210), (0, 0, 255), 3)

# Коло: центр, радіус, колір, товщина.
cv2.circle(canvas, (400, 150), 70, (0, 180, 0), 4)

# Еліпс: центр, довжини півосей, кут повороту, початковий/кінцевий кути.
cv2.ellipse(canvas, (570, 150), (80, 45), 20, 0, 360, (0, 120, 220), 3)

# Додаємо підпис. OpenCV Hershey fonts не підтримують кирилицю надійно,
# тому для цього прикладу використовуємо латиницю.
cv2.putText(
    canvas, "OpenCV drawing", (40, 300),
    cv2.FONT_HERSHEY_SIMPLEX, 1, (30, 30, 30), 2
)

cv2.imshow("Drawing primitives", canvas)
cv2.imwrite("drawing_example.png", canvas)
cv2.waitKey(0)
cv2.destroyAllWindows()
